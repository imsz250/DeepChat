/**
 * 手动配色：Google Material Color Utilities 的 SchemeTonalSpot 算法，
 * 从一颗种子色生成一整套 M3 色板（36 个色阶角色，和壁纸动态取色同一套算法，
 * 也就是 Material You 的那套全部颜色）。
 * Android 12 以下没有壁纸取色能力，靠这里的预设色补上；12 以上也能手动指定。
 */
enum class SeedColor(
    val key: String,
    val zh: String,
    val tw: String,
    val en: String,
    val seed: Long
) {
    DEFAULT("default", "默认蓝", "默認藍", "Blue", 0xFF3A56D4L),
    GREEN("green", "绿色", "綠色", "Green", 0xFF2E7D32L),
    YELLOW("yellow", "黄色", "黃色", "Yellow", 0xFFF5B301L),
    PURPLE("purple", "紫色", "紫色", "Purple", 0xFF7B3FF2L),
    PINK("pink", "粉色", "粉色", "Pink", 0xFFE44A8CL),
    TEAL("teal", "青色", "青色", "Teal", 0xFF00897BL),
    ;

    companion object {
        fun of(key: String?): SeedColor? = entries.firstOrNull { it.key == key }
    }
}

fun seedScheme(seed: SeedColor, dark: Boolean): ColorScheme = when (seed) {
    SeedColor.DEFAULT -> if (dark) dark_default else light_default
    SeedColor.GREEN -> if (dark) dark_green else light_green
    SeedColor.YELLOW -> if (dark) dark_yellow else light_yellow
    SeedColor.PURPLE -> if (dark) dark_purple else light_purple
    SeedColor.PINK -> if (dark) dark_pink else light_pink
    SeedColor.TEAL -> if (dark) dark_teal else light_teal
}

